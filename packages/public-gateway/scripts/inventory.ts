// Writes docs/route-classification.{json,md} from the OpenAPI spec.
// Usage: node scripts/inventory.ts <openapi-spec.json> <output-dir>
import { mkdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { loadInventory, type RouteClass } from '../src/inventory.ts';
import { decide } from '../src/policy.ts';

const [specPath, outDir] = process.argv.slice(2);
if (!specPath || !outDir) {
  console.error('Usage: node scripts/inventory.ts <openapi-spec.json> <output-dir>');
  process.exit(1);
}

const routes = loadInventory(specPath).map((route) => ({
  ...route,
  gateway: decide(route.method, route.path.replaceAll(/\{[^}]+\}/g, '00000000-0000-4000-8000-000000000000')).action,
}));

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'route-classification.json'), JSON.stringify(routes, null, 2) + '\n');

const classes: RouteClass[] = ['read', 'public', 'full', 'write', 'admin'];
const lines = [
  '# Noodle route classification',
  '',
  `Generated by \`pnpm inventory\` from \`${basename(specPath)}\` (${routes.length} operations).`,
  '`gateway` is what the public gateway does with the route when every feature is enabled.',
  '',
  '| Class | Count |',
  '|---|---|',
  ...classes.map((c) => `| ${c} | ${routes.filter((r) => r.class === c).length} |`),
];
for (const c of classes) {
  lines.push('', `## ${c}`, '', '| Method | Path | Permission | Gateway |', '|---|---|---|---|');
  for (const r of routes.filter((r) => r.class === c)) {
    lines.push(`| ${r.method} | \`${r.path}\` | ${r.permission ?? '-'} | ${r.gateway} |`);
  }
}
writeFileSync(join(outDir, 'route-classification.md'), lines.join('\n') + '\n');

for (const c of classes) {
  console.log(c.padEnd(7), routes.filter((r) => r.class === c).length);
}
